def mush_text(st):
    n = MUSHROOMS.get(L(st), 0)
    if L(st) == 1:
        return n, "На старой берёзе у тропы опята. Семь шляпок: две трухлявые, одна кривая, как ухо, и четыре крепких."
    if n == 3:
        return n, "Опята на берёзе. Семь шляпок, одна кривая, как ухо. Ты же их срывал... Только они стали мельче."
    if n == 2:
        return n, "Опята опять выросли. Водянистые, бледные. Как будто у берёзы кончаются силы."
    if n == 1:
        return n, "На берёзе один опёнок. Остальные почернели и сгнили на корню. И кривой, конечно, на месте."
    return 0, "Берёза пустая. Только кривой опёнок торчит, как ни в чём не бывало."


def a1_ferns(st):
    ui.header("Папоротники", tod(st))
    if L(st) == 1:
        ui.narr("Летом мы сворачивали у высоких папоротников. Первый снег пригнул их к земле, "
                "и теперь это белые горбы. Поворот не узнать.")
        ui.say("Зато на тропе маленькие следы, Сашины, с узорчатой подошвой. Она тут пробежала минут пять назад. "
               "Следы ведут мимо валуна, у которого летом был привал. Ты идёшь по ним.", C.GRY)
    elif L(st) == 2:
        ui.narr("Папоротники под снегом. Следы на тропе только твои, большие.")
        ui.thought("Утром тут были Сашины. Я точно видел. Куда она делась? Она что, дошла?")
    else:
        ui.narr("Белые горбы папоротников. Ты больше не ищешь поворот. Ты знаешь, что его нет.")
    n, text = mush_text(st)
    ui.say(text, C.MAG if L(st) > 1 else C.GRY)
    opts = []
    if n and not st.has("mush_loop_%d" % L(st)):
        opts.append(("mush", f"Собрать опята ({n}): пальцы замёрзнут, −1 тепло"))
    opts.append(("go", "Идти к валуну"))
    while True:
        k = ui.ask(opts, hidden={"сорвать кривой": "ear", "кривой": "ear", "ухо": "ear",
                                 "сорвать кривую": "ear"})
        if k == "mush":
            st.set("mush_loop_%d" % L(st))
            st.add("грибы", n)
            st.hurt(1)
            if st["warmth"] <= 0:
                st["warmth"] = 1
            ui.say(f"Ковыряешь опята из-под снега голыми пальцами. Кривой не трогаешь, жалко его. "
                   f"(+{n} {ui.plural(n, 'опёнок', 'опёнка', 'опят')}, −1 тепло)", C.YEL)
            opts = [o for o in opts if o[0] != "mush"]
            continue
        if k == "ear":
            if st.has("ear_loop_%d" % L(st)):
                ui.say("Его уже нет. До следующего раза.", C.GRY)
                continue
            st.set("ear_taken")
            st.set("ear_loop_%d" % L(st))
            st.add("грибы", 1)
            ui.say("Срываешь кривой. Он холодный и почему-то тёплый одновременно. (+1 опёнок)", C.YEL)
            if L(st) > 1:
                ui.say("Ты же срывал его в прошлый раз. А он снова тут. Единственный, кто не меняется.", C.MAG)
            continue
        break
    ui.transition("birch", "snow", "Лезешь через сугробы...")
    ui.header("Валун", "место летнего привала")
    ui.narr("Большой валун. Летом здесь ели бутерброды с сыром и спорили, кто дальше кинет шишку. "
            "Вокруг из-под снега торчат камни, гладкие, как раз по руке.")
    st.add("камень", 2)
    ui.say("Набираешь камней. (+2 камня)", C.YEL)
    if L(st) == 2 and not st.has("boulder_note"):
        st.set("boulder_note")
        ui.say("Под валуном что-то белеет. Бумажка, сложенная вчетверо. Почерк твой: "
               "«не трать камни на ручей. он там и так уже роется».", C.MAG)
        ui.thought("Я этого не писал. Я бы запомнил.")
    elif L(st) == 3:
        ui.say("Под валуном ещё одна записка. Твой почерк, но буквы кривее, будто писали замёрзшими руками: "
               "«кто вверх не смотрит, тот по кругу ходит. это не я придумал, это Ефим».", C.MAG)
    elif L(st) == 4:
        ui.say("Под валуном записка. Одно слово, обведённое три раза: «НАВЕРХ».", C.MAG)
    elif L(st) >= 5:
        ui.say("Под валуном целая пачка записок. Все твоим почерком. Ты не читаешь. Ты и так знаешь.", C.MAG)
    ui.pause()
    ui.transition("snow", "bog", "Слышно воду...")
    return "a1_stream"


