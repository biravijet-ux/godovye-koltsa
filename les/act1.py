def opyata(n):
    return f"{n} {ui.plural(n, 'опёнок', 'опёнка', 'опят')}"


def trade(st, who="Ефим", markup=0):
    goods = [
        ("tea", f"Кружка чая с чагой (+2 тепла) — {opyata(2 + markup)}", 2 + markup),
        ("stones", f"Три гладких камня — {opyata(1 + markup)}", 1 + markup),
        ("rope", f"Верёвка — {opyata(3 + markup)}", 3 + markup),
    ]
    first = True
    while True:
        ui.header(f"{who}: обмен", "")
        if first and st.get("mushrooms_traded", 0) and st["loop"] >= 3 and not st.has("act21"):
            ui.voice(who, "Опят у меня, кстати, полный мешок. Твоих же. Ну, давай ещё.")
