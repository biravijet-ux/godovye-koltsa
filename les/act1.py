# время суток по кругам: лес «вечереет», пока ты ходишь
TIME = {1: "полдень", 2: "после полудня", 3: "сумерки", 4: "темно", 5: "ночь"}
MUSHROOMS = {1: 4, 2: 3, 3: 2, 4: 1}


def L(st):
    return st["loop"]


def tod(st):
    return TIME.get(L(st), "ночь")


def dark(st):
    return L(st) >= 4


def helped_before(st):
    """Ты помог себе на гребне в прошлом круге — и сейчас услышишь это снизу."""
    return st.has("helped") and st.get("helped_loop", 99) < L(st)


def cool(st, text="Холодает. С каждым кругом всё холоднее. (−1 тепло)"):
    st.hurt(1)
    ui.say(text, C.BLU)
    if st["warmth"] <= 0:
        st["warmth"] = 2
        ui.danger("Ноги не слушаются. Ты садишься прямо в снег и долго растираешь руки, "
                  "пока пальцы снова не начинают гнуться. (тепло 2)")


def redraw(place, sub=""):
    ui.pause()
    ui.header(place, sub)


