def a1_stump(st):
    if L(st) >= KNOW_ALL:
        return a1_fast(st)
    ui.header("Старый пень", tod(st))
    if L(st) == 1:
        art.show(art.STUMP, C.WHT)
        ui.narr("Широкий пень у тропы. Летом на нём рос мох, и на нём было удобно сидеть, "
                "вытряхивая камешки из кед. Сейчас на нём шапка снега, как на торте.")
        ui.say("Летом отсюда было видно всю тропу, до самых берёз. Теперь снег пригнул ветки, "
               "и видно шагов на двадцать.", C.GRY)
    else:
        a, b, c = STUMP_TEXT[L(st)]
        ui.narr(a)
        ui.say(b, C.GRY)
        ui.thought(c)
        cool(st)
        if not st.n("фонарь") and st.has("threw_lantern"):
            ui.thought("Фонаря нет. Ну конечно, я же бросил его с гребня. Тому, внизу.")
    opts = []
    if not st.has("notch"):
        opts.append(("notch", "Вырезать ножом зарубку на пне, на память"))
    else:
        opts.append(("look", "Посмотреть на зарубку"))
    opts.append(("go", "Идти по тропе"))
    while True:
        k = ui.ask(opts, hidden={"сесть": "sit", "сесть на пень": "sit", "посидеть": "sit"})
        if k == "sit":
            n = st["sits"] = st.get("sits", 0) + 1
            ui.say(["Садишься на пень. Холодно. Встаёшь.",
                    "Опять садишься. Лес ждёт, пока ты насидишься. Он терпеливый.",
                    "Ты что, решил тут остаться? Так тоже можно. Многие так и остаются."]
                   [min(n - 1, 2)], C.GRY)
            continue
        break
    if k == "notch":
        st.set("notch")
        st["notch_loop"] = L(st)
        st["memory"]["пень"] = "нож"
        ui.say("Вырезаешь на боку пня косую черту, как летом на дубе. Нож идёт туго, пень промёрз.", C.YEL)
        ui.pause()
    elif k == "look":
        if st.get("notch_loop", 1) < L(st):
            ui.say("Зарубка на месте. Только... на другой стороне пня. Ты подошёл с той же стороны, "
                   "что и тогда, ты почти уверен.", C.MAG)
            st.set("saw_notch_moved")
        else:
            ui.say("Косая черта, дерево в ней ещё светлое.", C.GRY)
        ui.pause()
    ui.transition("birch", "birch", "Тропа ныряет под согнутые ветки...")
    return "a1_ferns"


def a1_fast(st):
    """«Ты всё знаешь»: решённые места пролетают одним экраном."""
    ui.header("Знакомая дорога", f"круг {L(st)}")
    ui.narr("Пень. Папоротники. Валун. Пустая берёза с одним кривым опёнком. Ручей. "
            "Ты знаешь здесь каждый сучок, каждую кочку. Ноги идут сами, голова свободна.")
    ui.say(["Ты пробуешь считать шаги. Сбиваешься на тысяче.",
            "Ты пробуешь идти с закрытыми глазами. Получается. Это пугает больше всего.",
            "Ты напеваешь что-то. Лес подпевает. Чуть-чуть фальшиво."][L(st) % 3], C.GRY)
    cool(st, "Холодно. (−1 тепло)")
    ui.thought("Хватит. По тропе отсюда не выйти. Я это знаю уже несколько кругов. "
               "Над ущельем гребень. Туда ведут мои собственные следы.")
    k = ui.ask([("fire", "Завернуть к костру Ефима погреться"), ("ravine", "Сразу к ущелью")])
    ui.transition("spruce", "spruce")
    return "a1_fire" if k == "fire" else "a1_ravine"


